"""
Нагрузка педагога в академических часах.

Считать её в астрономических часах — арифметически верно и практически
бесполезно: занятие в сорок минут превращалось в «0,67 часа», и педагог,
проведший полноценный урок, видел на экране две трети непонятно чего.
Между тем ставка у него за академический час, и урок он проводит один,
сколько бы минут в нём ни было — сорок, сорок пять или пятьдесят.

Поэтому здесь одна мера: академический час, сорок пять минут. Занятие
короче или равное ему считается за один час — за проведённый урок платят
как за урок. Длиннее — за столько часов, сколько в нём помещается, с
округлением вверх: полтора часа занятия это два академических, а не полтора,
потому что и готовятся к ним как к двум.
"""
from __future__ import annotations

import math
from decimal import Decimal

ACADEMIC_MINUTES = 45


def academic_hours(minutes: int | None) -> int:
    """Сколько академических часов в занятии такой длины."""
    minutes = int(minutes or 0)
    if minutes <= 0:
        return 0
    return max(1, math.ceil(minutes / ACADEMIC_MINUTES))


def hours_of(lessons) -> int:
    """
    Академические часы за несколько занятий.

    Считаем по каждому отдельно, а не по сумме минут: два урока по сорок
    минут это два часа, а вовсе не один час двадцать, как получилось бы,
    сложи мы сначала минуты.
    """
    return sum(academic_hours(lesson.duration_minutes) for lesson in lessons)


def payment_for(*, hours: int, rate: Decimal) -> Decimal:
    """Начисление за отработанные академические часы."""
    return (Decimal(hours) * Decimal(rate or 0)).quantize(Decimal("0.01"))
