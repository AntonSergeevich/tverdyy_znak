"""Проверки конфигурации, которые должны мешать выкатить небезопасное."""
from __future__ import annotations

from django.conf import settings
from django.core.checks import Error, Warning, register


@register
def two_factor_enabled(app_configs, **kwargs):
    """
    Второй фактор выключен — а в базе уже есть дети.

    Выключатель задумывался как временный, «на приёмку, пока данных нет».
    Так и вышло: его выключили, приёмка кончилась, дети появились, а
    выключатель остался — и владелец с администратором заходили по одному
    паролю. Напоминание в `check --deploy`, которое никто не запускает,
    от этого не спасло.

    Поэтому теперь проверка обычная, а не только для выката, и она ругается
    ошибкой, как только в базе появляется хоть один ученик. На проде
    выключатель вдобавок не действует вовсе — см. config/settings/prod.py.
    """
    if settings.TWO_FACTOR_ENABLED:
        return []

    hint = (
        "Верните TWO_FACTOR_ENABLED=True в .env и перезапустите web. "
        "Второй фактор обязателен для владельца, администратора и админа "
        "платформы: у них в кабинете персональные данные детей."
    )
    if _students_exist():
        return [
            Error(
                "Второй фактор выключен, а в базе есть ученики.",
                hint=hint,
                id="accounts.E001",
            )
        ]
    return [
        Warning(
            "Второй фактор выключен: TWO_FACTOR_ENABLED=False.",
            hint=hint + " Допустимо только пока в базе нет данных учеников.",
            id="accounts.W001",
        )
    ]


def _students_exist() -> bool:
    """
    Есть ли в базе дети.

    Проверка выполняется и там, где базы ещё нет: при первой сборке, до
    миграций, в чужом окружении. Недоступная база — не повод падать, но и
    не повод молчать: считаем, что данных нет, и остаёмся на уровне
    предупреждения.
    """
    try:
        from apps.journal.models import Student

        return Student.all_objects.exists()
    except Exception:  # noqa: BLE001 — до миграций падает по-разному, и это нормально
        return False
